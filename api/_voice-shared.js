export function readEnvKey() {
  const key = process.env.OPENAI_API_KEY;
  if (!key) {
    const err = new Error('서버에 OPENAI_API_KEY 환경변수가 설정되어 있지 않습니다.');
    err.statusCode = 500;
    throw err;
  }
  return key;
}
